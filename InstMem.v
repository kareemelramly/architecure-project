module InstMem (input [6:0] addr, output [31:0] data_out);
reg [31:0] mem [0:127];
integer i;
initial begin
        for (i = 0; i < 128; i = i + 1) mem[i] = 32'd0;

        // --- SETUP REGISTERS ---
        mem[0]  = 32'b000000000000_00000_010_00001_0000011; // lw x1, 0(x0)   -> x1 = 10
        mem[1]  = 32'b000000000100_00000_010_00010_0000011; // lw x2, 4(x0)   -> x2 = 20
        mem[2]  = 32'b000000001000_00000_010_00011_0000011; // lw x3, 8(x0)   -> x3 = -5 (0xFFFFFFFB)
        mem[3]  = 32'b0000000_00000_00000_000_00100_0110011; // add x4, x0, x0 -> x4 = 0 (Pass Score)
        mem[4]  = 32'b0000000_00000_00000_000_00101_0110011; // add x5, x0, x0 -> x5 = 0 (Fail/Trap Count)

        // --- TEST 1: BEQ (funct3 = 000) | 10 == 10 (TAKEN, +8) ---
        mem[5]  = 32'b0_000000_00001_00001_000_0100_0_1100011; // beq x1, x1, +8 (Jump to mem[7])
        mem[6]  = 32'b0000000_00001_00101_000_00101_0110011; // TRAP: add x5, x5, x1 (Skipped!)
        mem[7]  = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (x4 = 10)

        // --- TEST 2: BNE (funct3 = 001) | 10 != 20 (TAKEN, +8) ---
        mem[8]  = 32'b0_000000_00010_00001_001_0100_0_1100011; // bne x1, x2, +8 (Jump to mem[10])
        mem[9]  = 32'b0000000_00001_00101_000_00101_0110011; // TRAP: add x5, x5, x1 (Skipped!)
        mem[10] = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (x4 = 20)

        // --- TEST 3: BLT (funct3 = 100) | -5 < 10 Signed (TAKEN, +8) ---
        mem[11] = 32'b0_000000_00001_00011_100_0100_0_1100011; // blt x3, x1, +8 (Jump to mem[13])
        mem[12] = 32'b0000000_00001_00101_000_00101_0110011; // TRAP: add x5, x5, x1 (Skipped!)
        mem[13] = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (x4 = 30)

        // --- TEST 4: BGE (funct3 = 101) | 10 >= -5 Signed (TAKEN, +8) ---
        mem[14] = 32'b0_000000_00011_00001_101_0100_0_1100011; // bge x1, x3, +8 (Jump to mem[16])
        mem[15] = 32'b0000000_00001_00101_000_00101_0110011; // TRAP: add x5, x5, x1 (Skipped!)
        mem[16] = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (x4 = 40)

        // --- TEST 5: BLTU (funct3 = 110) | 10 < 0xFFFFFFFB Unsigned (TAKEN, +8) ---
        mem[17] = 32'b0_000000_00011_00001_110_0100_0_1100011; // bltu x1, x3, +8 (Jump to mem[19])
        mem[18] = 32'b0000000_00001_00101_000_00101_0110011; // TRAP: add x5, x5, x1 (Skipped!)
        mem[19] = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (x4 = 50)

        // --- TEST 6: BGEU (funct3 = 111) | 0xFFFFFFFB >= 20 Unsigned (TAKEN, +8) ---
        mem[20] = 32'b0_000000_00010_00011_111_0100_0_1100011; // bgeu x3, x2, +8 (Jump to mem[22])
        mem[21] = 32'b0000000_00001_00101_000_00101_0110011; // TRAP: add x5, x5, x1 (Skipped!)
        mem[22] = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (x4 = 60)

        // --- TEST 7: NOT-TAKEN CHECK | BLTU 0xFFFFFFFB < 10 Unsigned (FALSE -> NOT TAKEN) ---
        mem[23] = 32'b0_000000_00001_00011_110_0100_0_1100011; // bltu x3, x1, +8 (Must NOT jump!)
        mem[24] = 32'b0000000_00001_00100_000_00100_0110011; // PASS: add x4, x4, x1 (Executed! x4 = 70)

        // --- STORE FINAL RESULTS TO DATAMEM ---
        mem[25] = 32'b0000000_00100_00000_010_01100_0100011; // sw x4, 12(x0) -> DataMem[3] = 70
        mem[26] = 32'b0000000_00101_00000_010_10000_0100011; // sw x5, 16(x0) -> DataMem[4] = 0

        // --- TEST 8: LOAD BYTE / HALFWORD from DataMem[5] = 0x7C8AF1B2 (byte addr 20) ---
        mem[27] = 32'b000000010100_00000_000_00110_0000011; // lb  x6, 20(x0)  -> x6  = 0xFFFFFFB2 (sign extended byte 0)
        mem[28] = 32'b000000010111_00000_000_00111_0000011; // lb  x7, 23(x0)  -> x7  = 0x0000007C (positive byte 3)
        mem[29] = 32'b000000010100_00000_100_01000_0000011; // lbu x8, 20(x0)  -> x8  = 0x000000B2 (zero extended byte 0)
        mem[30] = 32'b000000010101_00000_100_01001_0000011; // lbu x9, 21(x0)  -> x9  = 0x000000F1 (zero extended byte 1)
        mem[31] = 32'b000000010100_00000_001_01010_0000011; // lh  x10, 20(x0) -> x10 = 0xFFFFF1B2 (sign extended half 0)
        mem[32] = 32'b000000010110_00000_001_01011_0000011; // lh  x11, 22(x0) -> x11 = 0x00007C8A (positive half 1)
        mem[33] = 32'b000000010100_00000_101_01100_0000011; // lhu x12, 20(x0) -> x12 = 0x0000F1B2 (zero extended half 0)
        mem[34] = 32'b000000010110_00000_101_01101_0000011; // lhu x13, 22(x0) -> x13 = 0x00007C8A (zero extended half 1)

        // --- TEST 9: STORE BYTE / HALFWORD (word 6 = bytes, word 7 = halves) + read back ---
        mem[35] = 32'b0000000_00001_00000_000_11000_0100011; // sb  x1, 24(x0)  -> DataMem[6] = 0x0000000A
        mem[36] = 32'b0000000_00010_00000_000_11001_0100011; // sb  x2, 25(x0)  -> DataMem[6] = 0x0000140A
        mem[37] = 32'b0000000_00011_00000_000_11010_0100011; // sb  x3, 26(x0)  -> DataMem[6] = 0x00FB140A
        mem[38] = 32'b0000000_00001_00000_000_11011_0100011; // sb  x1, 27(x0)  -> DataMem[6] = 0x0AFB140A
        mem[39] = 32'b0000000_00011_00000_001_11100_0100011; // sh  x3, 28(x0)  -> DataMem[7] = 0x0000FFFB
        mem[40] = 32'b0000000_00010_00000_001_11110_0100011; // sh  x2, 30(x0)  -> DataMem[7] = 0x0014FFFB
        mem[41] = 32'b000000011000_00000_010_01110_0000011; // lw  x14, 24(x0) -> x14 = 0x0AFB140A (reads back the sb results)
        mem[42] = 32'b000000011100_00000_010_01111_0000011; // lw  x15, 28(x0) -> x15 = 0x0014FFFB (reads back the sh results)

        // --- TEST 10: FENCE / FENCE.TSO / PAUSE are NOPs, then ECALL halts the PC ---
        mem[43] = 32'b0000_1111_1111_00000_000_00000_0001111; // fence iorw, iorw (NOP)
        mem[44] = 32'b1000_0011_0011_00000_000_00000_0001111; // fence.tso (NOP)
        mem[45] = 32'b0000_0001_0000_00000_000_00000_0001111; // pause (NOP)
        mem[46] = 32'b0000000_00010_00001_000_10000_0110011; // add x16, x1, x2 -> x16 = 30 (executes normally after the fences)
        mem[47] = 32'b0000001_10000_00000_010_00000_0100011; // sw  x16, 32(x0) -> DataMem[8] = 30
        mem[48] = 32'b0000000_00010_00001_100_10001_0110011; // xor x17, x1, x2 -> x17 = 30 (x1=10, x2=20 still intact)
        mem[49] = 32'b0000000_00010_00001_001_10011_0110011; // sll  x19, x1, x2 -> 10 << 20 = 0x00A00000
        mem[50] = 32'b0000000_00001_00011_010_10100_0110011; // slt  x20, x3, x1 -> -5 < 10 signed = 1
        mem[51] = 32'b0000000_00001_00011_011_10101_0110011; // sltu x21, x3, x1 -> 0xFFFFFFFB < 10 unsigned = 0
        mem[52] = 32'b0000000_00001_00011_101_10111_0110011; // srl  x23, x3, x1 -> 0xFFFFFFFB >> 10 = 0x003FFFFF
        mem[53] = 32'b0100000_00001_00011_101_11000_0110011; // sra  x24, x3, x1 -> -5 >>> 10 = 0xFFFFFFFF
        mem[54] = 32'b0000000_00011_00001_011_10110_0110011; // sltu x22, x1, x3 -> 1
        mem[55] = 32'b000000000101_00001_000_11001_0010011;  // addi x25, x1, 5   -> 15
        mem[56] = 32'b111111111101_00001_000_11010_0010011;  // addi x26, x1, -3  -> 7 (bit 30 = 1, must not become sub)
        mem[57] = 32'b000000001111_00001_100_11011_0010011;  // xori x27, x1, 15  -> 5
        mem[58] = 32'b000000000110_00001_111_11100_0010011;  // andi x28, x1, 6   -> 2
        mem[59] = 32'b000000000110_00001_110_11110_0010011;  // ori  x30, x1, 6   -> 14
        mem[60] = 32'b0000000_00100_00001_001_11101_0010011; // slli x29, x1, 4  -> 10 << 4 = 160 (0xA0)
        mem[61] = 32'b0000000_11111_00011_001_11111_0010011; // slli x31, x3, 31 -> 0xFFFFFFFB << 31 = 0x80000000

        // --- ADDITIONAL I-TYPE TESTS  ---
        mem[62] = 32'b111111111011_00001_010_00001_0010011; // slti  x1, x1, -5  -> 10 < -5 signed = 0
        mem[63] = 32'b000000001010_00011_011_00010_0010011; // sltiu x2, x3, 10  -> 0xFFFFFFFB < 10 unsigned = 0
        mem[64] = 32'b0000000_00100_00011_101_00011_0010011; // srli  x3, x3, 4   -> 0xFFFFFFFB >> 4 = 0x0FFFFFFF
        mem[65] = 32'b0100000_00010_00001_101_00100_0010011; // srai  x4, x1, 2   -> arithmetic shift right
        mem[66] = 32'b00010010001101000101_00101_0110111; // lui   x5, 0x12345 -> x5 = 0x12345000
        mem[67] = 32'b00000000000000000010_00110_0010111; // auipc x6, 0x2     -> x6 = PC + 0x2000
        mem[68] = 32'b000100010100_00000_000_00111_1100111; // jalr x7, 276(x0)
        // --- COMPLETE R-TYPE / JAL COVERAGE ---
        mem[69] = 32'b0100000_11010_11001_000_10010_0110011; // sub x18, x25, x26 -> 15 - 7 = 8
        mem[70] = 32'b0000000_11010_11001_111_10110_0110011; // and x22, x25, x26 -> 7
        mem[71] = 32'b0000000_11010_11001_110_10100_0110011; // or  x20, x25, x26 -> 15
        mem[72] = 32'h008000EF; // jal x1, +8 -> link = 292, jump to mem[74]
        mem[73] = 32'h00100913; // TRAP: addi x18, x0, 1 (Skipped!)
        mem[74] = 32'h0040006F; // jal x0, +4 -> discard link, jump to ECALL
        mem[75] = 32'b000000000000_00000_000_00000_1110011; // ecall (byte 300)
        mem[76] = 32'b0000000_00001_00001_000_10010_0110011; // add x18, x1, x1 -> must NOT exec
    end
assign data_out = mem[addr];
endmodule