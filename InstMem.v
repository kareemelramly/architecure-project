`timescale 1ns / 1ps

module InstMem (input [5:0] addr, output [31:0] data_out);
    reg [31:0] mem [0:63];
    integer i;

    initial begin
        for (i = 0; i < 64; i = i + 1) mem[i] = 32'd0;

        // 1. BASE LOADS
        mem[0]  = 32'b000000000000_00000_010_00001_0000011; // lw x1, 0(x0)  -> x1 = 10
        mem[1]  = 32'b000000000100_00000_010_00010_0000011; // lw x2, 4(x0)  -> x2 = 20
        mem[2]  = 32'b000000001000_00000_010_00011_0000011; // lw x3, 8(x0)  -> x3 = -5

        // 2. ARITHMETIC & LOGIC
        mem[3]  = 32'b0000000_00010_00001_000_00100_0110011; // add x4, x1, x2 -> x4 = 30
        mem[4]  = 32'b0100000_00001_00010_000_00101_0110011; // sub x5, x2, x1 -> x5 = 10
        mem[5]  = 32'b0000000_00101_00100_111_00110_0110011; // and x6, x4, x5 -> x6 = 30 & 10 = 10
        mem[6]  = 32'b0000000_00101_00100_110_00111_0110011; // or x7, x4, x5  -> x7 = 30 | 10 = 30

        // 3. CONDITIONAL BRANCHES (All branches skip exactly 1 instruction)
        mem[7]  = 32'b0_000000_00101_00001_000_0100_0_1100011; // beq x1, x5, +8 (10 == 10)
        mem[8]  = 32'b0000000_00001_11111_000_11111_0110011; // TRAP: add x31, x31, x1
        
        mem[9]  = 32'b0_000000_00010_00001_001_0100_0_1100011; // bne x1, x2, +8 (10 != 20)
        mem[10] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP: add x31, x31, x1
        
        mem[11] = 32'b0_000000_00001_00011_100_0100_0_1100011; // blt x3, x1, +8 (-5 < 10)
        mem[12] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP: add x31, x31, x1
        
        mem[13] = 32'b0_000000_00011_00001_101_0100_0_1100011; // bge x1, x3, +8 (10 >= -5)
        mem[14] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP: add x31, x31, x1
        
        mem[15] = 32'b0_000000_00011_00001_110_0100_0_1100011; // bltu x1, x3, +8 (10 < 4294967291)
        mem[16] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP: add x31, x31, x1
        
        mem[17] = 32'b0_000000_00001_00011_111_0100_0_1100011; // bgeu x3, x1, +8 (4294967291 >= 10)
        mem[18] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP: add x31, x31, x1

        // 4. U-TYPE (LUI, AUIPC)
        mem[19] = 32'b00010010001101000101_01000_0110111; // lui x8, 0x12345 -> x8 = 0x12345000
        mem[20] = 32'b00000000000000000010_01001_0010111; // auipc x9, 2 -> x9 = PC(80) + 0x2000 = 0x2050

        // 5. JUMPS (JAL, JALR)
        mem[21] = 32'b0_0000000110_0_00000000_01010_1101111; // jal x10, +12 -> PC=96 (mem[24]), link x10 = 88
        mem[22] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP
        mem[23] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP
        
        mem[24] = 32'b000001110000_00000_000_01100_1100111; // jalr x12, 112(x0) -> PC=112 (mem[28]), link x12 = 100
        mem[25] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP
        mem[26] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP
        mem[27] = 32'b0000000_00001_11111_000_11111_0110011; // TRAP

        // 6. STORES (Save final values for testbench checks)
        mem[28] = 32'b0000000_00100_00000_010_10000_0100011; // sw x4, 16(x0) -> DataMem[4] = 30
        mem[29] = 32'b0000000_00110_00000_010_10100_0100011; // sw x6, 20(x0) -> DataMem[5] = 10
        mem[30] = 32'b0000000_01000_00000_010_11000_0100011; // sw x8, 24(x0) -> DataMem[6] = 0x12345000
        mem[31] = 32'b0000000_01001_00000_010_11100_0100011; // sw x9, 28(x0) -> DataMem[7] = 0x2050
        mem[32] = 32'b0000001_01010_00000_010_00000_0100011; // sw x10, 32(x0) -> DataMem[8] = 88
        mem[33] = 32'b0000001_01100_00000_010_00100_0100011; // sw x12, 36(x0) -> DataMem[9] = 100
        mem[34] = 32'b0000001_11111_00000_010_01000_0100011; // sw x31, 40(x0) -> DataMem[10] = 0 (Errors)
    end

    assign data_out = mem[addr];
endmodule